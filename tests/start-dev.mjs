#!/usr/bin/env node
/**
 * Test-mode dev server: starts the local Resend mock + `vite dev` with the
 * .env.test environment applied. NO real email can be sent (Resend is
 * redirected to the local mock) and the production .env is never loaded from
 * this script — safety rule 0.
 *
 *   npm run dev:test
 *
 * Artifacts written to tests/.artifacts/ (gitignored):
 *   resend-payloads.jsonl  every email payload the app tried to send
 *   dev-server.json        { baseUrl, port, pid } for test harnesses
 *
 * The dev port is pinned to APP_URL from .env.test (default 5173) so captured
 * exam links match where the server actually listens.
 */
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import {
  loadTestEnv,
  assertNotProduction,
  parseEnvFile,
  ARTIFACTS_DIR,
  ROOT,
  writeJson,
} from "./lib/env.mjs";
import { createResendMockServer } from "./mocks/resend-mock-server.mjs";

loadTestEnv();
assertNotProduction(process.env.TURSO_DATABASE_URL);
for (const k of ["TURSO_DATABASE_URL", "SESSION_SECRET"]) {
  if (!process.env[k]) {
    console.error(`[dev:test] Missing ${k} — fill in .env.test (see .env.test.example).`);
    process.exit(1);
  }
}

if (!fs.existsSync(path.join(ROOT, "node_modules", "vite"))) {
  console.error("[dev:test] vite is not installed — run `bun install` or `npm install` first.");
  process.exit(1);
}

const appUrl = process.env.APP_URL ?? "http://localhost:5173";
let port = 5173;
try {
  port = Number(new URL(appUrl).port || 80);
} catch {
  /* keep default */
}
process.env.RESEND_API_KEY ??= "re_test_local_mock_not_a_real_key";
process.env.RESEND_FROM ??= "ExamPortal Tests <no-reply@loadtest.example>";
process.env.RESEND_BASE_URL ??= `http://127.0.0.1:${process.env.RESEND_MOCK_PORT ?? 4599}`;

// 1. Resend mock — fails fast on port conflict, guarantees zero real emails.
const mock = createResendMockServer();
const mockPort = await mock.listen(Number(process.env.RESEND_MOCK_PORT ?? 4599));
console.log(`[dev:test] Resend mock: http://127.0.0.1:${mockPort} (capture: ${mock.capturePath})`);
console.log("[dev:test] no request will ever reach api.resend.com — zero real emails");

// 2. Vite dev server with the test environment.
// Client-env isolation: generate tests/env/.env from .env.test's VITE_*
// values and boot vite with envDir pointed there, so the browser bundle
// NEVER sees the production VITE_* values from the root .env. Mode stays
// "development" — the TanStack/lovable stack serves SSR routes only in that
// mode (verified: `vite dev --mode test` => 404 on every route).
const envDir = path.join(ROOT, "tests", "env");
fs.mkdirSync(envDir, { recursive: true });
const viteEnvLines = Object.entries(parseEnvFile(path.join(ROOT, ".env.test")))
  .filter(([k]) => k.startsWith("VITE_"))
  .map(([k, v]) => `${k}="${v}"`);
fs.writeFileSync(
  path.join(envDir, ".env"),
  "# AUTO-GENERATED by tests/start-dev.mjs from .env.test — do not edit.\n" +
    viteEnvLines.join("\n") +
    "\n",
);
console.log(
  `[dev:test] client env dir: ${envDir} (${viteEnvLines.length} VITE_ vars from .env.test)`,
);

const child = spawn(
  process.execPath,
  [path.join(ROOT, "tests", "vite-dev-wrapper.mjs"), "--port", String(port), "--strictPort"],
  {
    cwd: ROOT,
    env: process.env,
    stdio: ["ignore", "pipe", "pipe"],
  },
);

let ready = false;
let buffered = "";
// Vite embeds ANSI colour codes INSIDE URLs (localhost:<esc>[1m5173) — strip
// them before matching or ready-detection never fires.
const ANSI = new RegExp(String.fromCharCode(27) + "\\[[0-9;]*m", "g");
function onChunk(chunk) {
  process.stdout.write(chunk);
  if (ready) return;
  buffered += chunk.toString().replace(ANSI, "");
  const m = buffered.match(/https?:\/\/[^\s]+:\d+/);
  if (m) {
    ready = true;
    const baseUrl = m[0].replace(/\/+$/, "");
    writeJson(path.join(ARTIFACTS_DIR, "dev-server.json"), {
      baseUrl,
      port,
      pid: child.pid,
      startedAt: new Date().toISOString(),
    });
    console.log(`\n[dev:test] READY: ${baseUrl}  (tests/.artifacts/dev-server.json written)`);
    console.log(`[dev:test] APP_URL=${process.env.APP_URL} — captured exam links use this host`);
  }
}
child.stdout.on("data", onChunk);
child.stderr.on("data", onChunk);

function killTree() {
  if (child.exitCode !== null) return;
  if (process.platform === "win32") {
    spawn("taskkill", ["/pid", String(child.pid), "/T", "/F"], { stdio: "ignore" });
  } else {
    child.kill("SIGTERM");
  }
}
async function shutdown() {
  killTree();
  await mock.close();
  process.exit(0);
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
child.on("exit", (code) => {
  mock.close().finally(() => process.exit(code ?? 0));
});
